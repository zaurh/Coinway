android {
    namespace = "com.zaurh.coinway"
    compileSdk = 37

    defaultConfig {
        // Must stay the same as the app already published on Google Play.
        applicationId = "com.zaurh.coinway"
        minSdk = 24
        targetSdk = 36
        // Must be higher than the versionCode currently live on Google Play (1.0.1 = 2).
        versionCode = 3
        versionName = "1.1.0"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    // Upload key credentials live in the git-ignored keystore.properties at the project root:
    //   storeFile=/absolute/path/to/upload-keystore.jks
    //   storePassword=...
    //   keyAlias=...
    //   keyPassword=...
    // Without it, use Android Studio's "Generate Signed App Bundle" as before.
    val keystoreProps = Properties().apply {
        val file = rootProject.file("keystore.properties")
        if (file.exists()) file.inputStream().use { load(it) }
    }

    signingConfigs {
        if (keystoreProps.isNotEmpty()) {
            create("release") {
                storeFile = file(keystoreProps.getProperty("storeFile"))
                storePassword = keystoreProps.getProperty("storePassword")
                keyAlias = keystoreProps.getProperty("keyAlias")
                keyPassword = keystoreProps.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            signingConfigs.findByName("release")?.let { signingConfig = it }
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    buildFeatures {
        compose = true
        buildConfig = true
    }
    packaging {
        resources {
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
        }
    }
}

